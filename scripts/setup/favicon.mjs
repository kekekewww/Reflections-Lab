import { mkdir, readFile, writeFile } from "node:fs/promises";

// Original Reflection Lab RL monogram; no fonts or third-party image assets.
// Both formats use this geometry and the canonical canvas/accent design tokens.
const tokenUrl = new URL("../../docs/05-ux/DESIGN_TOKENS.json", import.meta.url);
const tokens = JSON.parse(await readFile(tokenUrl, "utf8")).groups;
const canvas = tokens.color.canvas.$value;
const accent = tokens.color.accent.$value;
const radius = Number.parseFloat(tokens.radius.panel.$value);
if (![canvas, accent].every((color) => /^#[0-9A-Fa-f]{6}$/.test(color)))
  throw new Error("FAVICON_REQUIRES_OPAQUE_SRGB_TOKENS");
if (!Number.isFinite(radius) || radius < 0 || radius > 16)
  throw new Error("FAVICON_INVALID_CORNER_RADIUS");

const contours = [
  [
    [5, 8],
    [13, 8],
    [17, 12],
    [17, 16],
    [13.5, 19.5],
    [17, 24],
    [12.5, 24],
    [8.5, 19],
    [8.5, 24],
    [5, 24],
  ],
  [
    [8.5, 11.5],
    [12, 11.5],
    [13.5, 13],
    [13.5, 15],
    [12, 16.5],
    [8.5, 16.5],
  ],
  [
    [20, 8],
    [23.5, 8],
    [23.5, 20.5],
    [27, 20.5],
    [27, 24],
    [20, 24],
  ],
];
const path = contours
  .map((points) => `M${points.map((point) => point.join(" ")).join("L")}Z`)
  .join("");
const svg = `<!-- Generated by scripts/setup/favicon.mjs from docs/05-ux/DESIGN_TOKENS.json. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32">
  <rect width="32" height="32" rx="${radius}" fill="${canvas}"/>
  <path d="${path}" fill="${accent}" fill-rule="evenodd"/>
</svg>
`;
const rgb = (hex) => [1, 3, 5].map((offset) => Number.parseInt(hex.slice(offset, offset + 2), 16));
const background = rgb(canvas);
const foreground = rgb(accent);

function insideMonogram(x, y) {
  let inside = false;
  for (const points of contours) {
    for (let i = 0, j = points.length - 1; i < points.length; j = i++) {
      const [xi, yi] = points[i];
      const [xj, yj] = points[j];
      if (yi > y !== yj > y && x < ((xj - xi) * (y - yi)) / (yj - yi) + xi) inside = !inside;
    }
  }
  return inside;
}

function bitmap(size) {
  const maskStride = Math.ceil(size / 32) * 4;
  const pixels = Buffer.alloc(size * size * 4);
  const mask = Buffer.alloc(maskStride * size);
  const samples = 4;
  for (let row = 0; row < size; row++) {
    for (let column = 0; column < size; column++) {
      const total = [0, 0, 0];
      let covered = 0;
      for (let sy = 0; sy < samples; sy++) {
        for (let sx = 0; sx < samples; sx++) {
          const x = ((column + (sx + 0.5) / samples) * 32) / size;
          const y = ((row + (sy + 0.5) / samples) * 32) / size;
          const dx = Math.max(radius - x, 0, x - (32 - radius));
          const dy = Math.max(radius - y, 0, y - (32 - radius));
          if (dx * dx + dy * dy > radius * radius) continue;
          const color = insideMonogram(x, y) ? foreground : background;
          for (let channel = 0; channel < 3; channel++) total[channel] += color[channel];
          covered++;
        }
      }
      // ICO DIBs store bottom-up BGRA rows and a separately padded 1-bit AND mask.
      const offset = ((size - 1 - row) * size + column) * 4;
      for (let channel = 0; channel < 3; channel++)
        pixels[offset + 2 - channel] = covered ? Math.round(total[channel] / covered) : 0;
      pixels[offset + 3] = Math.round((covered * 255) / (samples * samples));
      if (covered === 0)
        mask[(size - 1 - row) * maskStride + (column >> 3)] |= 0x80 >> (column & 7);
    }
  }
  const header = Buffer.alloc(40);
  header.writeUInt32LE(40, 0);
  header.writeInt32LE(size, 4);
  header.writeInt32LE(size * 2, 8);
  header.writeUInt16LE(1, 12);
  header.writeUInt16LE(32, 14);
  header.writeUInt32LE(pixels.length + mask.length, 20);
  return Buffer.concat([header, pixels, mask]);
}

const sizes = [16, 32];
const images = sizes.map(bitmap);
const directory = Buffer.alloc(6 + sizes.length * 16);
directory.writeUInt16LE(1, 2);
directory.writeUInt16LE(sizes.length, 4);
let offset = directory.length;
for (let i = 0; i < sizes.length; i++) {
  const entry = 6 + i * 16;
  directory[entry] = directory[entry + 1] = sizes[i];
  directory.writeUInt16LE(1, entry + 4);
  directory.writeUInt16LE(32, entry + 6);
  directory.writeUInt32LE(images[i].length, entry + 8);
  directory.writeUInt32LE(offset, entry + 12);
  offset += images[i].length;
}
const ico = Buffer.concat([directory, ...images]);
const output = new URL("../../public/", import.meta.url);
const args = process.argv.slice(2);
if (args.length > 1 || (args.length === 1 && args[0] !== "--check"))
  throw new Error("Usage: node scripts/setup/favicon.mjs [--check]");
if (!args.length) await mkdir(output, { recursive: true });
for (const [name, contents] of [
  ["favicon.svg", Buffer.from(svg)],
  ["favicon.ico", ico],
]) {
  const target = new URL(name, output);
  if (args[0] === "--check") {
    if (!(await readFile(target)).equals(contents)) throw new Error(`FAVICON_STALE: ${name}`);
  } else await writeFile(target, contents);
}
console.log(
  `Favicon ${args.length ? "check" : "generation"} PASS (original RL, 16/32px ICO + SVG)`,
);
